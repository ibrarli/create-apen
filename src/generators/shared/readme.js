function stackRows(ctx) {
  const { frontend: fe, backend: be, extras } = ctx.config;
  const rows = [];
  if (fe) {
    rows.push(["Frontend", `${label(FRONTENDS, fe.framework)} (${fe.language === "ts" ? "TypeScript" : "JavaScript"})`]);
    rows.push(["Styling", label(STYLING, fe.styling)]);
    const state = fe.state.map((s) => (s === "pinia" ? "Pinia" : label(REACT_STATE, s)));
    if (state.length) rows.push(["State / data", state.join(", ")]);
    if (fe.framework !== "next") rows.push(["Routing", fe.router ? (fe.framework === "vue" ? "Vue Router" : "React Router") : "—"]);
    rows.push(["Frontend structure", label(FRONTEND_STRUCTURES, fe.structure)]);
    rows.push(["File naming", label(NAMING, fe.naming)]);
  }
  if (be) {
    rows.push(["Backend", `${label(BACKENDS, be.framework)}${be.language ? ` (${be.language === "ts" ? "TypeScript" : "JavaScript"})` : ""}`]);
    rows.push(["Database", `${DB_LABEL[be.database]}${dbHint(be)}`]);
    rows.push(["Backend architecture", label(BACKEND_ARCHITECTURES[be.framework], be.architecture)]);
  }
  const extra = [extras.includes("docker") && "Docker Compose", extras.includes("prettier") && "Prettier", extras.includes("ci") && "GitHub Actions"].filter(Boolean);
  if (extra.length) rows.push(["Tooling", extra.join(", ")]);
  return rows;
}

function dbHint(be) {
  const hint = DATABASES[be.framework].find((d) => d.value === be.database)?.hint;
  return hint && be.database !== "none" ? ` — ${hint}` : "";
}

function prerequisites(ctx) {
  const { frontend: fe, backend: be, extras } = ctx.config;
  const list = [];
  if (fe || be?.framework === "express" || ctx.fullstack) list.push("[Node.js](https://nodejs.org) 20+");
  if (be?.framework === "dotnet") list.push(`[.NET SDK](https://dotnet.microsoft.com/download) ${ctx.dotnetMajor}`);
  if (be?.framework === "fastapi") list.push("[Python](https://www.python.org) 3.10+");
  if (extras.includes("docker")) list.push("[Docker](https://docs.docker.com/get-docker/) (optional, for the database and containers)");
  else if (be && !["none", "sqlite"].includes(be.database)) list.push(`A running ${DB_LABEL[be.database]} server`);
  return list.map((l) => `- ${l}`).join("\n");
}

function backendRunSteps(ctx, local = false) {
  const be = ctx.config.backend;
  const pm = ctx.config.pm;
  const cd = ctx.fullstack && !local ? "cd backend\n" : "";
  if (be.framework === "express")
    return `\`\`\`bash
${cd}${pm} install
${runScript(pm, "dev")}       # http://localhost:${ctx.apiPort}/api
\`\`\``;
  if (be.framework === "dotnet")
    return `\`\`\`bash
${cd}dotnet restore
dotnet watch run --project ${ctx.backendInfo.apiDir}   # http://localhost:${ctx.apiPort}/api
\`\`\`

Try the endpoints with \`${ctx.backendInfo.apiDir}/${ctx.backendInfo.apiProject}.http\` (VS Code REST Client / Rider / Visual Studio). The OpenAPI document is served at \`/openapi/v1.json\` in Development.`;
  return `\`\`\`bash
${cd}python3 -m venv .venv
source .venv/bin/activate          # Windows: .venv\\Scripts\\activate
pip install -r requirements.txt
uvicorn app.main:app --reload --port ${ctx.apiPort}   # http://localhost:${ctx.apiPort}/api
\`\`\`

Interactive API docs: http://localhost:${ctx.apiPort}/docs`;
}

function quickStart(ctx) {
  const { config } = ctx;
  const fe = config.frontend;
  const be = config.backend;
  const pm = config.pm;
  const docker = config.extras.includes("docker");
  const db = be && !["none", "sqlite"].includes(be.database);
  const out = [`## Getting started

### Prerequisites

${prerequisites(ctx)}`];

  const steps = [];
  if (db) {
    steps.push(
      docker
        ? `**1. Start the database**\n\n\`\`\`bash\ndocker compose up -d db\n\`\`\``
        : `**1. Start ${DB_LABEL[be.database]}** and make sure the connection string in ${be.framework === "dotnet" ? "`appsettings.json`" : "`.env`"} points to it.`
    );
  }
  const n = db ? 2 : 1;
  if (ctx.fullstack) {
    const backendSetup =
      be.framework === "fastapi"
        ? `\`\`\`bash\ncd backend\npython3 -m venv .venv && .venv/bin/pip install -r requirements.txt\ncd ..\n\`\`\`\n\n`
        : be.framework === "dotnet"
          ? `\`\`\`bash\ndotnet restore backend/${ctx.backendInfo.N}.sln\n\`\`\`\n\n`
          : "";
    steps.push(`**${n}. Install dependencies** (skip if you let the CLI install them)

\`\`\`bash
${pm} install
cd frontend && ${pm} install && cd ..
${be.framework === "express" ? `cd backend && ${pm} install && cd ..\n` : ""}\`\`\`

${backendSetup}**${n + 1}. Run everything**

\`\`\`bash
${runScript(pm, "dev")}
\`\`\`

This starts both apps with [concurrently](https://github.com/open-cli-tools/concurrently):

| App | URL |
| --- | --- |
| Frontend | http://localhost:${ctx.frontendPort} |
| API | http://localhost:${ctx.apiPort}/api |
| Health check | http://localhost:${ctx.apiPort}/api/health |

Prefer separate terminals? Run \`${runScript(pm, "dev:frontend")}\` and \`${runScript(pm, "dev:backend")}\`.`);
  } else if (fe) {
    steps.push(`**${n}. Install & run**

\`\`\`bash
${pm} install
${runScript(pm, "dev")}   # http://localhost:${ctx.frontendPort}
\`\`\`

The starter page calls \`/api/users\`. Point it at your API with \`API_URL\` (dev proxy) or \`${fe.framework === "next" ? "NEXT_PUBLIC_API_URL" : "VITE_API_URL"}\`.`);
  } else {
    steps.push(`**${n}. Install & run**\n\n${backendRunSteps(ctx, true)}`);
  }
  out.push(`### Run locally\n\n${steps.join("\n\n")}`);

  if (docker) {
    out.push(`### Run with Docker

\`\`\`bash
docker compose up --build
\`\`\`

${[
  fe && `- Frontend → http://localhost:${ctx.frontendPort}${fe.framework === "next" ? "" : " (nginx, proxies `/api` to the backend)"}`,
  be && `- API → http://localhost:${ctx.apiPort}/api`,
  ctx.dockerInfo?.database && `- ${DB_LABEL[ctx.dockerInfo.database]} → \`${ctx.dockerInfo.dbImage}\`, data kept in the \`db-data\` volume`,
]
  .filter(Boolean)
  .join("\n")}

Stop with \`docker compose down\` (add \`-v\` to also delete the database volume).`);
  }
  return out.join("\n\n");
}

function folderTable(ctx, side, heading) {
  const info = side === "frontend" ? ctx.frontendInfo : ctx.backendInfo;
  const pre = ctx.fullstack ? `${side}/` : "";
  const rows = info.folders.map(([dir, text]) => `| \`${pre}${dir}\` | ${text} |`);
  return `${heading}\n\n| Path | Purpose |\n| --- | --- |\n${rows.join("\n")}`;
}

function flowSection(ctx) {
  const { frontend: fe, backend: be } = ctx.config;
  const fpre = ctx.fullstack ? "frontend/" : "";
  const bpre = ctx.fullstack ? "backend/" : "";
  const lines = ["## How a request flows", ""];
  const dbName = be ? DB_LABEL[be.database] : null;

  if (fe) {
    const f = ctx.frontendInfo.flowFiles;
    const hookWord = fe.framework === "vue" ? "composable" : "hook";
    lines.push(
      `The starter screen lists users. Here is every hop of that request${be ? "" : " on the frontend"}, with the file that owns it:`,
      "",
      "```mermaid",
      "sequenceDiagram",
      "    autonumber",
      "    participant C as Component",
      `    participant H as ${hookWord === "hook" ? "Hook" : "Composable"}`,
      "    participant S as Service",
      "    participant A as apiClient",
      ...(be ? ["    participant R as API route", "    participant B as Backend logic", `    participant D as ${dbName === "None (in-memory)" ? "In-memory store" : dbName}`] : ["    participant R as Your API"]),
      `    C->>H: use${fe.framework === "vue" ? "" : ""}Users()`,
      "    H->>S: list()",
      "    S->>A: GET /users",
      "    A->>R: fetch /api/users",
      ...(be
        ? [
            `    R->>B: ${be.framework === "fastapi" ? "Depends(get_user_service)" : "controller / handler"}`,
            "    B->>D: query users",
            "    D-->>B: rows",
            "    B-->>R: users",
          ]
        : []),
      '    R-->>A: { "data": [...] }',
      "    A-->>S: User[]",
      "    S-->>H: User[]",
      "    H-->>C: { users, isLoading, error }",
      "```",
      "",
      "**Frontend**",
      "",
      `1. **Component** — \`${fpre}${f.component}\` renders the list and calls the ${hookWord}. It never calls \`fetch\` itself.`,
      `2. **${hookWord === "hook" ? "Hook" : "Composable"}** — \`${fpre}${f.hook}\` owns loading/error state${fe.state?.includes("query") ? " via TanStack Query (cached under the `users` key)" : ""}.`,
      `3. **Service** — \`${fpre}${f.service}\` maps one backend resource to functions (\`list\`, \`create\`).`,
      `4. **API client** — \`${fpre}${f.client}\` is the single \`fetch\` wrapper: base URL, JSON headers, unwraps \`{ data }\`, throws \`ApiError\` on \`{ error }\`.`,
      `5. **Proxy** — in development \`/api\` is forwarded to the backend by ${fe.framework === "next" ? "Next.js rewrites" : "the Vite dev server"}${ctx.config.extras.includes("docker") && fe.framework !== "next" ? "; in Docker by nginx" : ""}, so there are no CORS issues in the browser.`,
      ""
    );
  }

  if (be) {
    if (!fe) {
      lines.push("Every request travels through the same layers:", "");
    } else {
      lines.push("**Backend**", "");
    }
    ctx.backendInfo.flowFiles.forEach(([name, file], i) => {
      lines.push(`${i + 1}. **${name}** — \`${bpre}${file}\``);
    });
    lines.push(
      "",
      `Errors thrown anywhere (validation, *email already exists* → 409, unexpected) are turned into \`{ "error": { "message": "..." } }\` by one global handler.`
    );
  }
  return lines.join("\n");
}

function frontendConventions(ctx) {
  const fe = ctx.config.frontend;
  const structure = FRONTEND_STRUCTURES.find((s) => s.value === fe.structure);
  const naming =
    fe.naming === "kebab"
      ? "Every file and folder is **kebab-case**: `user-card.tsx`, `use-users.ts`, `api-client.ts`. Exported identifiers keep their normal casing (`UserCard`, `useUsers`)."
      : "**Components are PascalCase** (`UserCard.tsx`), everything else is **camelCase** (`useUsers.ts`, `apiClient.ts`). Folders are lowercase.";
  return `### Frontend conventions

- **Structure — ${structure.label}.** ${structure.description}
- **Naming.** ${naming.replace(/\.tsx/g, fe.framework === "vue" ? ".vue" : fe.language === "ts" ? ".tsx" : ".jsx").replace(/\.ts\b/g, fe.language === "ts" ? ".ts" : ".js")}
- **Imports** use the \`@/\` alias for \`src/\` (configured in ${fe.framework === "next" ? "`tsconfig`/`jsconfig`" : "`vite.config` and `tsconfig`/`jsconfig`"}).${fe.structure === "feature" ? "\n- **Feature boundaries.** Import a feature through its `index` file (`@/features/users`), never its internals." : ""}
- **Data access.** Components → ${fe.framework === "vue" ? "composables" : "hooks"} → services → \`apiClient\`. Only \`apiClient\` knows about \`fetch\`.
- **Styling.** ${
    fe.styling === "tailwind"
      ? "Tailwind utility classes; brand tokens (`brand-blue`, `brand-orange`) live in the `@theme` block of the global stylesheet."
      : fe.styling === "modules"
        ? fe.framework === "vue"
          ? "Scoped `<style>` blocks inside each SFC."
          : "One `*.module.css` file next to each component, imported as `styles`."
        : "One global stylesheet with BEM class names (`block__element`)."
  }`;
}

function backendConventions(ctx) {
  const be = ctx.config.backend;
  const arch = BACKEND_ARCHITECTURES[be.framework].find((a) => a.value === be.architecture);
  const naming = {
    express:
      be.architecture === "clean"
        ? "Files are **kebab-case** (`create-user.ts`); classes are PascalCase (`CreateUser`)."
        : "Files use **dot-suffix naming** by role: `user.controller`, `user.service`, `user.repository`.",
    dotnet: "Standard .NET conventions: **PascalCase** files/types, one public type per file, `I`-prefixed interfaces, `Async` suffix for async methods.",
    fastapi: "Standard Python conventions: **snake_case** modules and functions, PascalCase classes, one package per layer/module.",
  }[be.framework];
  return `### Backend conventions

- **Architecture — ${arch.label}.** ${arch.description}
- **Naming.** ${naming}
- **Responses** are always wrapped: \`{ "data": ... }\` on success, \`{ "error": { "message": "..." } }\` on failure.
- **Validation** happens at the edge (${{ express: "Zod schemas", dotnet: "DataAnnotations on request DTOs", fastapi: "Pydantic schemas" }[be.framework]}) before business logic runs.`;
}

function conventions(ctx) {
  const parts = ["## Conventions"];
  if (ctx.config.frontend) parts.push(frontendConventions(ctx));
  if (ctx.config.backend) parts.push(backendConventions(ctx));
  return parts.join("\n\n");
}

