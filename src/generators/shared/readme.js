// README generation: root README plus per-app READMEs for full-stack repos.
import {
  FRONTENDS,
  BACKENDS,
  DATABASES,
  STYLING,
  FRONTEND_STRUCTURES,
  BACKEND_ARCHITECTURES,
  NAMING,
  REACT_STATE,
  label,
} from "../../catalog.js";
import { runScript } from "../../utils/exec.js";
import { devBackend } from "./root.js";

const DB_LABEL = { mongodb: "MongoDB", postgres: "PostgreSQL", mysql: "MySQL", sqlserver: "SQL Server", sqlite: "SQLite", none: "None (in-memory)" };

export function generateReadmes(ctx) {
  const { project, config } = ctx;
  // Placeholders first, so the READMEs show up in the folder tree.
  project.add("README.md", "");
  if (ctx.fullstack) {
    project.add("frontend/README.md", "");
    project.add("backend/README.md", "");
  }

  if (ctx.fullstack) {
    project.add("frontend/README.md", appReadme(ctx, "frontend"));
    project.add("backend/README.md", appReadme(ctx, "backend"));
  }
  project.add("README.md", rootReadme(ctx));
  void config;
}

function rootReadme(ctx) {
  const { config } = ctx;
  const fe = config.frontend;
  const be = config.backend;
  const parts = [];

  parts.push(`# ${ctx.title}

> Scaffolded with **create-apen** by [Apen Apps](https://www.apenapps.com) — ${ctx.stack.join(" · ")}`);

  parts.push(`## Stack

| Layer | Choice |
| --- | --- |
${stackRows(ctx)
  .map(([k, v]) => `| ${k} | ${v} |`)
  .join("\n")}`);

  parts.push(quickStart(ctx));
  parts.push(`## Project structure

\`\`\`text
${ctx.packageName}/
${ctx.project.tree("", { maxDepth: ctx.fullstack ? 5 : 6 })}
\`\`\``);

  if (fe) parts.push(folderTable(ctx, "frontend", ctx.fullstack ? "### Frontend folders" : "### Folders"));
  if (be) parts.push(folderTable(ctx, "backend", ctx.fullstack ? "### Backend folders" : "### Folders"));

  parts.push(flowSection(ctx));
  parts.push(conventions(ctx));
  parts.push(addFeature(ctx));
  parts.push(scriptsSection(ctx));
  if (config.extras.includes("env")) parts.push(envSection(ctx));

  parts.push(`---

<sub>Generated by \`create-apen\`. Edit this README freely — it is yours now.</sub>`);
  return parts.join("\n\n") + "\n";
}

